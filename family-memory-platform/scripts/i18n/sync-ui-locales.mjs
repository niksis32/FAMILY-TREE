/**
 * Sync i18n registry: scan locales/*.json → messages.ts + geonames uiTranslated
 *
 *   pnpm i18n:sync-ui-locales
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LOCALE_UI_FALLBACK as MANUAL_FALLBACK } from './locale-fallback-data.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const localesDir = join(root, 'apps/web/i18n/locales');
const messagesTs = join(root, 'apps/web/i18n/messages.ts');
const geonamesJson = join(root, 'packages/shared/src/data/geonames-locales.json');

const SLAVIC = new Set([
  'uk', 'be', 'pl', 'cs', 'sk', 'hr', 'sr', 'sl', 'bg', 'mk', 'bs', 'kk', 'ky', 'tg', 'mn', 'mo',
]);
const ROMANCE_ES = new Set(['pt', 'gl', 'oc', 'ca', 'an', 'ast']);
const ROMANCE_FR = new Set(['it', 'rm', 'ro', 'fr', 'ht', 'co', 'sc', 'vec', 'lad', 'fur']);
const GERMANIC = new Set(['nl', 'da', 'sv', 'no', 'nb', 'nn', 'fi', 'is', 'lb', 'af', 'fy', 'nds', 'gsw']);
const RTL = new Set(['he', 'fa', 'ur', 'ps', 'ku', 'dv', 'yi']);
const CJK = new Set(['zh', 'ja', 'ko', 'vi', 'th', 'id', 'ms', 'hi', 'bn', 'ta', 'te', 'ml', 'kn', 'gu', 'pa', 'my', 'km', 'lo', 'ne', 'si', 'bo', 'dz']);

function inferFallback(code, fileSet) {
  if (fileSet.has(code)) return null;
  if (MANUAL_FALLBACK[code]) return MANUAL_FALLBACK[code];
  if (SLAVIC.has(code)) return fileSet.has('ru') ? 'ru' : 'en';
  if (ROMANCE_ES.has(code)) return fileSet.has('es') ? 'es' : 'en';
  if (ROMANCE_FR.has(code)) return fileSet.has('fr') ? 'fr' : 'en';
  if (GERMANIC.has(code)) return fileSet.has('de') ? 'de' : 'en';
  if (RTL.has(code)) return fileSet.has('ar') ? 'ar' : 'en';
  if (CJK.has(code)) return fileSet.has('zh') ? 'zh' : fileSet.has('ja') ? 'ja' : fileSet.has('ko') ? 'ko' : 'en';
  if (code === 'tr' || code === 'az' || code === 'uz') return fileSet.has('tr') ? 'tr' : fileSet.has('de') ? 'de' : 'en';
  if (code === 'el' || code === 'sq' || code === 'hy') return fileSet.has('fr') ? 'fr' : 'en';
  if (code === 'hu' || code === 'et' || code === 'lv' || code === 'lt') return fileSet.has('de') ? 'de' : fileSet.has('ru') ? 'ru' : 'en';
  return 'en';
}

function buildFullFallbackMap(fileSet) {
  const geonames = JSON.parse(readFileSync(geonamesJson, 'utf8'));
  const out = { ...MANUAL_FALLBACK };
  for (const code of geonames.codes) {
    if (code === 'en') continue;
    const inferred = inferFallback(code, fileSet);
    if (inferred && inferred !== code) out[code] = inferred;
  }
  return out;
}

function main() {
  const files = readdirSync(localesDir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => f.replace(/\.json$/, ''))
    .sort((a, b) => (a === 'en' ? -1 : b === 'en' ? 1 : a.localeCompare(b)));

  const fileSetArr = files;
  const fileSetLiteral = fileSetArr.map((c) => JSON.stringify(c)).join(', ');
  const fullFallback = buildFullFallbackMap(new Set(fileSetArr));

  writeFileSync(
    messagesTs,
    `/** Auto-generated by pnpm i18n:sync-ui-locales — do not edit by hand */
import enMessages from './locales/en.json';
import { LOCALE_UI_FALLBACK } from './locale-fallback';

export const UI_MESSAGE_LOCALE_FILES = [${fileSetLiteral}] as const;

export type UiMessageLocaleFile = (typeof UI_MESSAGE_LOCALE_FILES)[number];

const fileSet = new Set<string>(UI_MESSAGE_LOCALE_FILES);

type MessageTree = Record<string, unknown>;

/** Fill gaps in auto-generated locale files (formHints, localeGroups, …) from en. */
function deepMergeMessages(base: MessageTree, override: MessageTree): MessageTree {
  const result: MessageTree = { ...base };
  for (const [key, value] of Object.entries(override)) {
    if (
      value !== null &&
      typeof value === 'object' &&
      !Array.isArray(value) &&
      typeof result[key] === 'object' &&
      result[key] !== null &&
      !Array.isArray(result[key])
    ) {
      result[key] = deepMergeMessages(result[key] as MessageTree, value as MessageTree);
    } else {
      result[key] = value;
    }
  }
  return result;
}

/**
 * Resolve locale to an on-disk messages file (direct file or mapped fallback).
 */
export function resolveUiMessageLocale(locale: string, visited = new Set<string>()): string {
  if (visited.has(locale)) return 'en';
  visited.add(locale);
  if (fileSet.has(locale)) return locale;
  const mapped = LOCALE_UI_FALLBACK[locale];
  if (mapped) return resolveUiMessageLocale(mapped, visited);
  return 'en';
}

export async function loadUiMessages(locale: string) {
  const target = resolveUiMessageLocale(locale);
  if (target === 'en') return enMessages;
  try {
    const mod = await import(\`./locales/\${target}.json\`);
    const loaded = (mod.default ?? mod) as MessageTree;
    return deepMergeMessages(enMessages as MessageTree, loaded) as typeof enMessages;
  } catch {
    return enMessages;
  }
}
`,
    'utf8',
  );

  writeFileSync(
    join(root, 'apps/web/i18n/locale-fallback.ts'),
    `/** Auto-generated by pnpm i18n:sync-ui-locales */
export const LOCALE_UI_FALLBACK: Record<string, string> = ${JSON.stringify(fullFallback, null, 2)};
`,
    'utf8',
  );

  if (existsSync(geonamesJson)) {
    const data = JSON.parse(readFileSync(geonamesJson, 'utf8'));
    data.uiTranslated = files;
    writeFileSync(geonamesJson, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
  }

  console.log(`UI message locale files (${files.length}): ${files.slice(0, 12).join(', ')}${files.length > 12 ? '…' : ''}`);
  console.log(`Wrote ${messagesTs}`);
}

main();
