/**
 * Sync UI message locales: scan apps/web/i18n/locales/*.json → messages.ts + geonames-locales.json uiTranslated
 *
 *   pnpm i18n:sync-ui-locales
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const localesDir = join(root, 'apps/web/i18n/locales');
const messagesTs = join(root, 'apps/web/i18n/messages.ts');
const geonamesJson = join(root, 'packages/shared/src/data/geonames-locales.json');

function main() {
  const codes = readdirSync(localesDir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => f.replace(/\.json$/, ''))
    .sort((a, b) => (a === 'en' ? -1 : b === 'en' ? 1 : a.localeCompare(b)));

  const imports = codes.map((c) => `import ${c}Messages from './locales/${c}.json';`).join('\n');
  const entries = codes.map((c) => `  ${c}: ${c}Messages,`).join('\n');

  writeFileSync(
    messagesTs,
    `/** Auto-generated by pnpm i18n:sync-ui-locales — do not edit by hand */\n${imports}\n\nexport const UI_MESSAGE_LOCALES = ${JSON.stringify(codes)} as const;\n\nexport type UiMessageLocale = (typeof UI_MESSAGE_LOCALES)[number];\n\nexport const UI_MESSAGES: Record<UiMessageLocale, typeof enMessages> = {\n${entries}\n};\n\nexport function loadUiMessages(locale: string) {\n  if (locale in UI_MESSAGES) return UI_MESSAGES[locale as UiMessageLocale];\n  return UI_MESSAGES.en;\n}\n`,
    'utf8',
  );

  if (existsSync(geonamesJson)) {
    const data = JSON.parse(readFileSync(geonamesJson, 'utf8'));
    data.uiTranslated = codes;
    writeFileSync(geonamesJson, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
  }

  console.log(`UI message locales (${codes.length}): ${codes.join(', ')}`);
  console.log(`Wrote ${messagesTs}`);
}

main();
